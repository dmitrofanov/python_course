"""
Дан список. Проверь, является ли он палиндромом
(читается одинаково слева направо и справа налево).
"""

tests = [
    [1, 2, 3, 2, 1],
    [1, 2, 3, 4, 5],
    ['a', 'b', 'c', 'b', 'a'],
    ['a', 'b', 'c', 'd', 'e']
]

for test in tests:
    is_palindrom = test == test[::-1]
    print(test, is_palindrom)