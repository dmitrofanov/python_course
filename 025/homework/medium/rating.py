"""
Дан список результатов игр в формате "победитель, проигравший".
Подсчитай количество побед для каждого игрока.
"""
games = [
    ("Анна", "Иван"),
    ("Мария", "Петр"),
    ("Анна", "Мария"),
    ("Иван", "Петр"),
    ("Анна", "Петр"),
    ("Мария", "Иван"),
]

result = {}

for winner, _ in games:
    result[winner] = result.get(winner, 0) + 1
print(result)
