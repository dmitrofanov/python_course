"""
Дано слово и список букв. Проверь, все ли буквы из списка есть в слове.
Если какой-то буквы нет — выведи её.
"""

word = "программирование"
letters = ["п", "р", "о", "г", "а", "м", "и", "с", "е", "н", "т"]

rest = []
for letter in letters:
    if letter not in word:
        rest.append(letter)

print(f'букв {rest} нет в слове')